package com.ato.ui_state.wishlist

import com.ato.ui_state.Ui
import com.ato.ui_state.base.text.UiSimpleText

data class UiBoard(
    val board: WishlistBoard?,
    val boardName: UiSimpleText,
    val boardWishCount: UiSimpleText,
    /**
     * Пометка «основная» — или ничего, если доска обычная.
     *
     * Строкой, а не `Boolean`: подпись всё равно пришлось бы брать из ресурсов,
     * а до них слой отрисовки в `sonic_ui` не достаёт — `common_resources`
     * живёт в приложении. Заодно поле само отвечает на «рисовать или нет»,
     * ровно как [privacy] рядом.
     *
     * У основной доски может не быть своего имени, и тогда она и так
     * называется «Основная» — но стоит её переименовать, и по списку уже не
     * скажешь, куда поедет желание, если доску не выбирать. Об этом и пометка.
     *
     * Заполняется только для своих досок: на чужой странице знать, какая из
     * досок у человека основная, незачем.
     */
    val mainBadge: UiSimpleText? = null,
    /**
     * Кому видна доска — целой фразой: «Видно всем», «Видно только вам».
     *
     * Фразой, а не названием аудитории. Сначала здесь лежало короткое «Всем»,
     * и на карточке оно стояло пилюлей рядом с «Основная» — из чего никак не
     * следовало, что речь про видимость: «Выбранным: 3» читалось как непонятный
     * тег с числом. Слово «Видно» и есть ответ на вопрос, которого не возникало.
     *
     * Тоже только для своих досок. Видимость — свойство, которым владелец
     * управляет, и место ему там, где он видит все свои доски сразу; на чужой
     * странице это лишняя строка про чужие настройки.
     */
    val privacy: UiSimpleText? = null,
): Ui